const CANVAS = { n8n: 'n8n', knime: 'knime', 'pi-agent': 'pi' }

export const PLATFORMS = PLATFORM_LIST.map(meta => ({
  ...meta,
  Canvas: CANVAS[meta.id],
  workflow: WORKFLOWS[meta.id],
}))

export function getPlatformById(platformKey) {
  const id = platformKey === 'pi' ? 'pi-agent' : platformKey
  return PLATFORMS.find(p => p.id === id) || null
}
